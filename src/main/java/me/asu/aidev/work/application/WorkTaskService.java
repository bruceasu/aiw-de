package me.asu.aidev.work.application;

import me.asu.aidev.work.domain.TaskDependency;
import me.asu.aidev.work.domain.TaskId;
import me.asu.aidev.work.domain.TaskState;
import me.asu.aidev.work.domain.WorkTask;
import me.asu.aidev.work.port.TaskDependencyRepository;
import me.asu.aidev.work.port.WorkTaskRepository;
import java.time.Clock;
import java.util.UUID;
import java.util.Set;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

@Service
public class WorkTaskService {
    private me.asu.aidev.execution.skills.SkillFiles skillFiles;
    @Autowired public void setSkillFiles(me.asu.aidev.execution.skills.SkillFiles value) { skillFiles=value; }
    private org.springframework.beans.factory.ObjectProvider<me.asu.aidev.execution.guard.ExecutionGuard> executionGuard;
    @Autowired
    public void setExecutionGuard(org.springframework.beans.factory.ObjectProvider<me.asu.aidev.execution.guard.ExecutionGuard> guard) { this.executionGuard=guard; }
    private me.asu.aidev.authority.ManagedPlanAdmission managedPlans;
    @Autowired
    public void setManagedPlanAdmission(me.asu.aidev.authority.ManagedPlanAdmission gate) { this.managedPlans=gate; }
    private final WorkTaskRepository tasks;
    private final TaskDependencyRepository dependencies;
    private final DependencyResolver dependencyResolver;
    private final Clock clock;

    @Autowired
    public WorkTaskService(WorkTaskRepository tasks,
                           TaskDependencyRepository dependencies,
                           DependencyResolver dependencyResolver) {
        this(tasks, dependencies, dependencyResolver, Clock.systemUTC());
    }

    WorkTaskService(WorkTaskRepository tasks,
                    TaskDependencyRepository dependencies,
                    DependencyResolver dependencyResolver,
                    Clock clock) {
        this.tasks = tasks;
        this.dependencies = dependencies;
        this.dependencyResolver = dependencyResolver;
        this.clock = clock;
    }

    @Transactional
    public WorkTask create(CreateWorkTaskCommand command) {
        return createInternal(command, false);
    }

    @Transactional public WorkTask createReplacing(CreateWorkTaskCommand command,TaskId source) {
        return createInternal(command,false,source);
    }

    /**
     * Idempotent materialization for deterministic tasks generated by completion handlers.
     * Replaying the same completion event must not create duplicate work or fail on primary keys.
     */
    @Transactional
    public WorkTask createIfAbsent(CreateWorkTaskCommand command) {
        return createInternal(command, true);
    }

    private WorkTask createInternal(CreateWorkTaskCommand command, boolean idempotent) {
        return createInternal(command,idempotent,null);
    }
    private WorkTask createInternal(CreateWorkTaskCommand command, boolean idempotent,TaskId source) {
        if(executionGuard!=null) executionGuard.getObject().beforeTaskCreation(command);
        if (managedPlans!=null && "flexible-plan".equals(command.subjectType())) managedPlans.admitTask(command.subjectId(),command.id().value());
        var now = clock.instant();
        TaskState initialState = command.dependencies().isEmpty() ? TaskState.READY : TaskState.BLOCKED;
        WorkTask task = new WorkTask(
                command.id(), command.type(), initialState,
                command.subjectType(), command.subjectId(), command.requiredCapabilities(), command.skillRef(), command.instruction(),
                command.repositoryRef(), command.baseRevision(), command.priority(), 0, now, now);

        boolean inserted = true;
        if (idempotent) {
            inserted = tasks.insertIfAbsent(task);
            if (!inserted) {
                WorkTask existing = tasks.find(task.id())
                        .orElseThrow(() -> new IllegalStateException("task disappeared after insert conflict: " + task.id().value()));
                assertCompatibleGeneratedTask(command, existing);
                if (!Set.copyOf(dependencies.findDependencies(task.id())).equals(command.dependencies())) {
                    throw new IllegalStateException("deterministic generated task id collision with incompatible dependencies: "
                            + task.id().value());
                }
            }
        } else {
            tasks.insert(task);
        }
        if(inserted && executionGuard!=null) executionGuard.getObject().taskCreated(command);
        if(inserted && skillFiles!=null) {
            if(source==null) skillFiles.created(task);else skillFiles.inherit(source.value(),task.id().value());
        }

        command.dependencies().stream().sorted((a, b) -> a.value().compareTo(b.value()))
                .forEach(dependsOn -> {
                    TaskDependency dependency = new TaskDependency(task.id(), dependsOn);
                    if (idempotent) dependencies.insertIfAbsent(dependency);
                    else dependencies.insert(dependency);
                });

        // A dependent task may be created after one or all predecessors have already completed.
        // Resolve readiness after dependency edges exist so that no completion notification can be lost.
        if (!command.dependencies().isEmpty()) {
            dependencyResolver.refreshAfterCreation(task.id());
        }
        return tasks.find(task.id())
                .orElseThrow(() -> new IllegalStateException("task not found after create: " + task.id().value()));
    }

    private static void assertCompatibleGeneratedTask(CreateWorkTaskCommand command, WorkTask existing) {
        if (existing.type() != command.type()
                || !existing.subjectType().equals(command.subjectType())
                || !existing.subjectId().equals(command.subjectId())
                || !existing.requiredCapabilities().equals(command.requiredCapabilities())
                || !java.util.Objects.equals(existing.skillRef(), command.skillRef())
                || !java.util.Objects.equals(existing.instruction(), command.instruction())
                || !java.util.Objects.equals(existing.repositoryRef(), command.repositoryRef())
                || !java.util.Objects.equals(existing.baseRevision(), command.baseRevision())
                || !java.util.Objects.equals(existing.priority(), command.priority())) {
            throw new IllegalStateException("deterministic generated task id collision with incompatible task: "
                    + command.id().value());
        }
    }

    @Transactional(readOnly = true)
    public WorkTask get(me.asu.aidev.work.domain.TaskId taskId) {
        return tasks.find(taskId).orElseThrow(() -> new IllegalStateException("task not found: " + taskId.value()));
    }

    @Transactional
    public WorkTask createCorrection(TaskId completedTaskId, String instruction, String actor, String reason) {
        if (actor == null || actor.isBlank()) throw new IllegalArgumentException("actor is required");
        if (reason == null || reason.isBlank()) throw new IllegalArgumentException("reason is required");
        if (instruction == null || instruction.isBlank()) throw new IllegalArgumentException("correction instruction is required");
        WorkTask original = get(completedTaskId);
        if (original.state() != TaskState.COMPLETED) {
            throw new IllegalStateException("correction tasks can only follow a completed task");
        }
        TaskId correctionId = new TaskId("correction-" + UUID.randomUUID());
        WorkTask correction = create(new CreateWorkTaskCommand(
                correctionId, original.type(), original.subjectType(), original.subjectId(),
                original.requiredCapabilities(), original.skillRef(), instruction,
                original.repositoryRef(), original.baseRevision(), original.priority(), Set.of(completedTaskId)));
        tasks.linkCorrection(completedTaskId, correctionId, actor.strip(), reason.strip(), clock.instant());
        tasks.recordControlEvent(UUID.randomUUID().toString(), completedTaskId, null,
                "CORRECTION_CREATED", actor.strip(), reason.strip(), false, clock.instant());
        return correction;
    }
}
